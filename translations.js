function setLanguage(lang) {
  localStorage.setItem('georgio-lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });
  // Update nav title attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('title', translations[lang][key]);
    }
  });
  // Highlight active button
  document.querySelectorAll('.lang-switcher button').forEach(btn => {
    btn.style.opacity = '0.5';
  });
  const langMap = { 'ro': '🇷🇴', 'en': '🇬🇧', 'it': '🇮🇹' };
  document.querySelectorAll('.lang-switcher button').forEach(btn => {
    if (btn.textContent.trim() === langMap[lang]) {
      btn.style.opacity = '1';
    }
  });
}

// Init on load
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('georgio-lang') || 'it';
  setLanguage(saved);

  document.querySelectorAll('.lang-switcher button').forEach(btn => {
    btn.addEventListener('click', function() {
      const flag = this.textContent.trim();
      const langMap = { '🇷🇴': 'ro', '🇬🇧': 'en', '🇮🇹': 'it' };
      const lang = langMap[flag];
      if (lang) setLanguage(lang);
    });
  });
});
